"""
calculate_redis_metrics.py
============================
Redis NUMA benchmark results analysis script.

This script reads files generated by run_redis_benchmark.sh and calculates:
  - Total energy (J) with RAPL wraparound correction
  - Energy per request (nJ/req)
  - IPC (Instructions Per Cycle) of the Redis process
  - Throughput (requests per second)
  - Average and P99 latency
  - Comparison with baseline data

Input:  ~/k8s-numa-benchmark/results/redis/*.csv, *.txt
Output: Terminal table + CSV + summary plot

Author: Part of the k8s-numa-benchmark project
"""

