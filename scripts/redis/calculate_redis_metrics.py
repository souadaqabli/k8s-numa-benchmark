# ============================================================
# DATA STRUCTURES
# ============================================================
@dataclass
class RedisMetrics:
    """Contains all metrics for a scenario."""
    scenario: str
    energy_joules: float
    throughput_get: float
    throughput_set: float
    latency_avg_us: float
    latency_p50_us: float
    latency_p99_us: float
    instructions: int
    cycles: int
    cache_misses: int
    llc_misses: int
    ipc: float
    cache_miss_rate: float
    nj_per_req: float
    total_requests: int
    benchmark_duration_sec: float


# ============================================================
# PARSING FUNCTIONS
# ============================================================
def parse_rapl_files(before_path: str, after_path: str) -> float:
    """
    Calculate total energy in Joules from RAPL before/after files.
    Handles 32-bit RAPL counter wraparound.
    
    Returns:
        Total energy in Joules (PKG0+PKG1+DRAM0+DRAM1)
    """
    def read_rapl(path: str) -> tuple:
        with open(path) as f:
            line = f.read().strip()
            parts = line.split(',')
            return tuple(int(p.strip()) for p in parts)

    before = read_rapl(before_path)
    after = read_rapl(after_path)

    total_uj = 0
    for b_val, a_val in zip(before, after):
        delta = a_val - b_val
        if delta < 0:
            # Wraparound detected: counter rolled over to zero
            delta += RAPL_WRAPAROUND
        total_uj += delta

    return total_uj / 1_000_000.0  # Convert to Joules


def parse_benchmark_file(filepath: str) -> dict:
    """
    Extract metrics from redis-benchmark output file.
    
    Expected format:
        ====== GET ======
        ...
        throughput summary: 85322.12 requests per second
        ...
        ====== SET ======
        ...
        throughput summary: 81234.56 requests per second
    """
    metrics = {
        'throughput_get': 0.0,
        'throughput_set': 0.0,
        'latency_avg_us': 0.0,
        'latency_p50_us': 0.0,
        'latency_p99_us': 0.0,
        'total_requests': 0,
    }

    if not os.path.exists(filepath):
        return metrics

    with open(filepath) as f:
        content = f.read()

    # Throughput GET
    m = re.search(r'GET.*?([\d.]+)\s+requests per second', content, re.DOTALL)
    if m:
        metrics['throughput_get'] = float(m.group(1))

    # Throughput SET
    m = re.search(r'SET.*?([\d.]+)\s+requests per second', content, re.DOTALL)
    if m:
        metrics['throughput_set'] = float(m.group(1))

    # Average latency (format: "avg: 45.23")
    m = re.search(r'avg[=:]\s*([\d.]+)', content)
    if m:
        metrics['latency_avg_us'] = float(m.group(1))

    # P50 latency
    m = re.search(r'p50[=:]\s*([\d.]+)', content)
    if m:
        metrics['latency_p50_us'] = float(m.group(1))

    # P99 latency
    m = re.search(r'p99[=:]\s*([\d.]+)', content)
    if m:
        metrics['latency_p99_us'] = float(m.group(1))

    # Total number of requests
    m = re.search(r'(\d+)\s+requests completed', content)
    if m:
        metrics['total_requests'] = int(m.group(1))
    else:
        # Fallback: 100000 if using -n 100000
        metrics['total_requests'] = 100000

    return metrics


def parse_perf_file(filepath: str) -> dict:
    """
    Extract hardware counters from perf stat output file.
    
    Expected format:
        1,234,567,890      instructions
        987,654,321      cycles
        ...
    """
    metrics = {
        'instructions': 0,
        'cycles': 0,
        'cache_misses': 0,
        'llc_misses': 0,
        'cpu_clock': 0.0,
    }

    if not os.path.exists(filepath) or os.path.getsize(filepath) == 0:
        return metrics

    with open(filepath) as f:
        content = f.read()

    # Instructions
    m = re.search(r'([\d,]+)\s+instructions', content)
    if m:
        metrics['instructions'] = int(m.group(1).replace(',', ''))

    # Cycles
    m = re.search(r'([\d,]+)\s+cycles[\s\n]', content)
    if m:
        metrics['cycles'] = int(m.group(1).replace(',', ''))

    # Cache misses (L1/L2/L3 general)
    m = re.search(r'([\d,]+)\s+cache-misses', content)
    if m:
        metrics['cache_misses'] = int(m.group(1).replace(',', ''))

    # LLC misses (L3 specific)
    m = re.search(r'([\d,]+)\s+LLC-load-misses', content)
    if m:
        metrics['llc_misses'] = int(m.group(1).replace(',', ''))

    # CPU clock (msec)
    m = re.search(r'([\d,]+\.?\d*)\s+msec cpu-clock', content)
    if m:
        metrics['cpu_clock'] = float(m.group(1).replace(',', ''))

    return metrics


# ============================================================
# DERIVED METRICS CALCULATION
# ============================================================
def calculate_metrics(scenario: str) -> Optional[RedisMetrics]:
    """
    Calculate all metrics for a given scenario.
    
    Args:
        scenario: Scenario name (baseline, extreme, cross, extreme-cross)
        
    Returns:
        RedisMetrics if files exist, None otherwise
    """
    prefix = os.path.join(RESULTS_DIR, scenario)
    before_file = f"{prefix}_rapl_before.csv"
    after_file = f"{prefix}_rapl_after.csv"
    bench_file = f"{prefix}_benchmark.txt"
    perf_file = f"{prefix}_perf.csv"

    # Check that essential files exist
    if not os.path.exists(before_file) or not os.path.exists(after_file):
        print(f"[WARN] Missing RAPL files for {scenario}")
        return None

    # 1. RAPL energy (with wraparound)
    energy_j = parse_rapl_files(before_file, after_file)

    # 2. Benchmark metrics
    bench = parse_benchmark_file(bench_file)

    # 3. Perf counters
    perf = parse_perf_file(perf_file)

    # 4. Derived calculations
    total_requests = bench['total_requests']
    nj_per_req = (energy_j / total_requests * 1e9) if total_requests > 0 else 0.0

    ipc = perf['instructions'] / perf['cycles'] if perf['cycles'] > 0 else 0.0

    cache_refs = perf['instructions']  # Approximation if cache-references not available
    cache_miss_rate = (perf['cache_misses'] / cache_refs * 100) if cache_refs > 0 else 0.0

    # Estimated benchmark duration
    duration_sec = 30.0  # Default (perf sleep 30)
    if bench['throughput_get'] > 0:
        duration_sec = total_requests / bench['throughput_get']

    return RedisMetrics(
        scenario=scenario,
        energy_joules=energy_j,
        throughput_get=bench['throughput_get'],
        throughput_set=bench['throughput_set'],
        latency_avg_us=bench['latency_avg_us'],
        latency_p50_us=bench['latency_p50_us'],
        latency_p99_us=bench['latency_p99_us'],
        instructions=perf['instructions'],
        cycles=perf['cycles'],
        cache_misses=perf['cache_misses'],
        llc_misses=perf['llc_misses'],
        ipc=ipc,
        cache_miss_rate=cache_miss_rate,
        nj_per_req=nj_per_req,
        total_requests=total_requests,
        benchmark_duration_sec=duration_sec,
    )


