# DISPLAY AND EXPORT
# ============================================================
def print_results_table(results: List[RedisMetrics]):
    """Display a formatted comparison table in the terminal."""
    print("\n" + "=" * 120)
    print("  REDIS NUMA BENCHMARK RESULTS")
    print("=" * 120)

    # Header
    header = (
        f"{'Scenario':<16} "
        f"{'Energy(J)':>10} "
        f"{'GET(req/s)':>12} "
        f"{'Lat_avg(us)':>11} "
        f"{'Lat_p99(us)':>11} "
        f"{'IPC':>6} "
        f"{'nJ/req':>10} "
        f"{'vs Base':>8}"
    )
    print(header)
    print("-" * 120)

    # Find reference (baseline)
    baseline_nj = None
    for r in results:
        if r.scenario == "baseline":
            baseline_nj = r.nj_per_req
            break

    # Rows
    for r in results:
        vs_baseline = ""
        if baseline_nj and baseline_nj > 0:
            pct = ((r.nj_per_req - baseline_nj) / baseline_nj) * 100
            vs_baseline = f"+{pct:.0f}%" if pct > 0 else f"{pct:.0f}%"

        row = (
            f"{r.scenario:<16} "
            f"{r.energy_joules:>10.2f} "
            f"{r.throughput_get:>12.0f} "
            f"{r.latency_avg_us:>11.1f} "
            f"{r.latency_p99_us:>11.1f} "
            f"{r.ipc:>6.3f} "
            f"{r.nj_per_req:>10.1f} "
            f"{vs_baseline:>8}"
        )
        print(row)

    print("-" * 120)

    # Summary
    if baseline_nj:
        print(f"\n  [REFERENCE] baseline: {baseline_nj:.1f} nJ/req")
        for r in results:
            if r.scenario != "baseline":
                pct = ((r.nj_per_req - baseline_nj) / baseline_nj) * 100
                status = "BETTER" if pct < 0 else "WORSE"
                print(f"  [{status}] {r.scenario}: {r.nj_per_req:.1f} nJ/req ({pct:+.0f}%)")

    print("=" * 120)


def export_csv(results: List[RedisMetrics]):
    """Export results to CSV format."""
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    csv_path = os.path.join(OUTPUT_DIR, "redis_numa_results.csv")

    with open(csv_path, 'w', newline='') as f:
        writer = csv.writer(f)
        writer.writerow([
            'scenario', 'energy_joules', 'throughput_get', 'throughput_set',
            'latency_avg_us', 'latency_p99_us', 'instructions', 'cycles',
            'ipc', 'cache_misses', 'llc_misses', 'nj_per_req',
            'total_requests', 'duration_sec'
        ])
        for r in results:
            writer.writerow([
                r.scenario, r.energy_joules, r.throughput_get, r.throughput_set,
                r.latency_avg_us, r.latency_p99_us, r.instructions, r.cycles,
                r.ipc, r.cache_misses, r.llc_misses, r.nj_per_req,
                r.total_requests, r.benchmark_duration_sec
            ])

    print(f"\n[OK] Results exported to: {csv_path}")


def generate_summary_plot(results: List[RedisMetrics]):
    """Generate a summary plot if matplotlib is available."""
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
    except ImportError:
        print("[INFO] matplotlib not installed. No plot generated.")
        print("       Install it with: pip install matplotlib")
        return

    os.makedirs(OUTPUT_DIR, exist_ok=True)

    scenarios = [r.scenario for r in results]
    energies = [r.energy_joules for r in results]
    throughputs = [r.throughput_get for r in results]
    latencies = [r.latency_avg_us for r in results]
    nj_reqs = [r.nj_per_req for r in results]
    ipcs = [r.ipc for r in results]

    # Style configuration
    colors = ['#2E86AB', '#A23B72', '#F18F01', '#C73E1D']
    x = np.arange(len(scenarios))
    width = 0.35

    fig, axes = plt.subplots(2, 2, figsize=(14, 10))
    fig.suptitle('Redis NUMA Benchmark Results', fontsize=14, fontweight='bold')

    # 1. Total energy
    ax = axes[0, 0]
    bars = ax.bar(scenarios, energies, color=colors, edgecolor='black')
    ax.set_ylabel('Energy (Joules)', fontweight='bold')
    ax.set_title('Total Energy Consumption', fontweight='bold')
    ax.tick_params(axis='x', rotation=15)
    for bar, val in zip(bars, energies):
        ax.text(bar.get_x() + bar.get_width()/2., val + 1,
                f'{val:.1f}', ha='center', va='bottom', fontsize=9)

    # 2. Throughput
    ax = axes[0, 1]
    bars = ax.bar(scenarios, throughputs, color=colors, edgecolor='black')
    ax.set_ylabel('Throughput (req/s)', fontweight='bold')
    ax.set_title('GET Throughput', fontweight='bold')
    ax.tick_params(axis='x', rotation=15)
    for bar, val in zip(bars, throughputs):
        ax.text(bar.get_x() + bar.get_width()/2., val + 500,
                f'{val:.0f}', ha='center', va='bottom', fontsize=9)

    # 3. Average latency
    ax = axes[1, 0]
    bars = ax.bar(scenarios, latencies, color=colors, edgecolor='black')
    ax.set_ylabel('Latency (μs)', fontweight='bold')
    ax.set_title('Average Latency', fontweight='bold')
    ax.tick_params(axis='x', rotation=15)
    for bar, val in zip(bars, latencies):
        ax.text(bar.get_x() + bar.get_width()/2., val + 2,
                f'{val:.1f}', ha='center', va='bottom', fontsize=9)

    # 4. nJ/req
    ax = axes[1, 1]
    bars = ax.bar(scenarios, nj_reqs, color=colors, edgecolor='black')
    ax.set_ylabel('Energy per Request (nJ/req)', fontweight='bold')
    ax.set_title('Energy Efficiency per Request', fontweight='bold')
    ax.tick_params(axis='x', rotation=15)
    for bar, val in zip(bars, nj_reqs):
        ax.text(bar.get_x() + bar.get_width()/2., val + 5,
                f'{val:.0f}', ha='center', va='bottom', fontsize=9)

    # Reference line for nJ/req (baseline)
    if len(nj_reqs) > 0:
        ax.axhline(y=nj_reqs[0], color='red', linestyle='--', alpha=0.5,
                   label=f'Baseline ({nj_reqs[0]:.0f} nJ/req)')
        ax.legend()

    plt.tight_layout()
    plot_path = os.path.join(OUTPUT_DIR, "redis_numa_summary.png")
    plt.savefig(plot_path, dpi=300, bbox_inches='tight')
    print(f"[OK] Summary plot: {plot_path}")


